create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id bigint generated by default as identity primary key,
  auth_user_id uuid not null unique,
  full_name text not null,
  email text not null unique,
  phone text,
  company_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.client_profiles (
  id bigint generated by default as identity primary key,
  profile_id bigint not null unique references public.profiles(id) on delete cascade,
  account_status text not null default 'active' check (account_status in ('active', 'pending', 'paused', 'closed')),
  legal_focus text,
  preferred_contact text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.news_events (
  id bigint generated by default as identity primary key,
  title text not null,
  summary text not null,
  category text not null check (category in ('news', 'event')),
  published_at timestamptz not null default now(),
  image_url text,
  content text,
  created_by bigint references public.profiles(id) on delete set null
);

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  title text not null,
  booking_type text not null default 'consultation' check (booking_type in ('consultation', 'review', 'advisory', 'meeting')),
  start_at timestamptz not null,
  end_at timestamptz,
  mode text not null default 'virtual' check (mode in ('virtual', 'office', 'phone')),
  status text not null default 'scheduled' check (status in ('scheduled', 'confirmed', 'completed', 'cancelled')),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.invoices (
  id bigint generated by default as identity primary key,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  invoice_number text not null unique,
  amount numeric(12,2) not null default 0,
  status text not null default 'pending' check (status in ('pending', 'paid', 'overdue', 'cancelled')),
  issue_date date not null default current_date,
  due_date date,
  created_at timestamptz not null default now()
);

create table if not exists public.documents (
  id bigint generated by default as identity primary key,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  file_name text not null,
  file_url text not null,
  document_type text not null default 'legal-document',
  uploaded_at timestamptz not null default now(),
  is_private boolean not null default true
);

create table if not exists public.support_tickets (
  id bigint generated by default as identity primary key,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  subject text not null,
  status text not null default 'open' check (status in ('open', 'in_progress', 'resolved', 'closed')),
  priority text not null default 'normal' check (priority in ('low', 'normal', 'high', 'urgent')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.support_messages (
  id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.support_tickets(id) on delete cascade,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  message text not null,
  sent_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  title text not null,
  body text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create or replace function public.current_user_profile_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select id from public.profiles where auth_user_id = auth.uid() limit 1;
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (auth_user_id, full_name, email)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1)),
    new.email
  )
  on conflict (auth_user_id) do nothing;

  insert into public.client_profiles (profile_id, account_status)
  select id, 'active'
  from public.profiles
  where auth_user_id = new.id
  on conflict (profile_id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create index if not exists idx_profiles_auth_user_id on public.profiles(auth_user_id);
create index if not exists idx_client_profiles_profile_id on public.client_profiles(profile_id);
create index if not exists idx_bookings_profile_id on public.bookings(profile_id);
create index if not exists idx_invoices_profile_id on public.invoices(profile_id);
create index if not exists idx_documents_profile_id on public.documents(profile_id);
create index if not exists idx_support_tickets_profile_id on public.support_tickets(profile_id);
create index if not exists idx_notifications_profile_id on public.notifications(profile_id);
